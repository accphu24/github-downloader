/// Dịch 1 khoá sang ngôn ngữ hiện tại. Có thể truyền [params] để thay thế
/// các chỗ {tenBien} trong chuỗi gốc bằng giá trị thật.
String t(String key, [Map<String, String>? params]) {
  final lang = AppSettings.instance.locale;
  final dict = lang == 'en' ? _en : _vi;
  var text = dict[key] ?? _vi[key] ?? key;
  if (params != null) {
    params.forEach((k, v) => text = text.replaceAll('{$k}', v));
  }
  return text;
}

